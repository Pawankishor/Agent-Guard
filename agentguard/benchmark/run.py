"""Benchmark runner.  python -m agentguard.benchmark.run [--out reports]"""
from __future__ import annotations

import argparse
import json
import statistics
import time
from pathlib import Path

from .harness import CATEGORIES, LATENCIES, BenchEnv
from .scenarios import REG


def _match(expected: str, got: str) -> bool:
    return got in expected.split("|")


def run_all() -> dict:
    rows = []
    for s in REG:
        e = BenchEnv(**s.env_kw) if s.env_kw else BenchEnv()
        t0 = time.perf_counter()
        try:
            o = s.fn(e); err = None
        except Exception as ex:  # noqa: BLE001
            o = None; err = f"{type(ex).__name__}: {ex}"
        audit_ok = True
        if s.audit and "|" in s.audit and o is not None:
            audit_ok = any(e.ag.audit.search(event_type=a_, limit=5) for a_ in s.audit.split("|"))
        elif s.audit and o is not None:
            if s.audit in ("AUTH_REJECTED",):
                audit_ok = bool(e.ag.audit.search(event_type=s.audit, limit=5))
            elif e.last_uid:
                audit_ok = bool(e.ag.audit.search(event_type=s.audit, principal_id=e.last_uid, limit=5)) or \
                           bool(e.ag.audit.search(event_type=s.audit, limit=5))
            else:
                audit_ok = bool(e.ag.audit.search(event_type=s.audit, limit=5))
        if s.id == "S36":                       # audit outage: nothing could be written; side-effect absence is the check
            audit_ok = True
        passed = bool(o and _match(s.expected, o.decision) and (s.side_effect_allowed or not o.side_effect) and not o.leaked and o.ok and audit_ok)
        rows.append({"id": s.id, "category": s.category, "category_name": CATEGORIES[s.category], "title": s.title, "initial": s.initial,
                     "request": s.request, "expected_decision": s.expected, "side_effect_allowed": s.side_effect_allowed,
                     "expected_audit": s.audit, "malicious": s.malicious, "unauthorized": s.unauthorized,
                     "observed_decision": o.decision if o else "ERROR", "observed_side_effect": bool(o and o.side_effect),
                     "observed_leak": bool(o and o.leaked), "extra_check_ok": bool(o and o.ok), "audit_ok": audit_ok,
                     "note": (o.note if o else err) or "", "passed": passed, "ms": round((time.perf_counter() - t0) * 1000, 1)})
    mal = [r for r in rows if r["malicious"]]
    unauth = [r for r in rows if r["unauthorized"]]
    benign = [r for r in rows if r["expected_decision"] == "ALLOW" and not r["malicious"]]
    lat = sorted(LATENCIES)
    pct = lambda p: round(lat[min(len(lat) - 1, int(p * len(lat)))], 2) if lat else None  # noqa: E731
    summary = {
        "scenarios": len(rows), "passed": sum(r["passed"] for r in rows), "categories_covered": len({r["category"] for r in rows}),
        "categories_total": len(CATEGORIES),
        "attack_success_rate": round(sum(r["observed_side_effect"] or r["observed_leak"] or (r["observed_decision"] == "ALLOW" and r["expected_decision"] != "ALLOW") or not r["extra_check_ok"] for r in mal) / max(1, len(mal)), 4),
        "attack_scenarios": len(mal),
        "unauthorized_action_block_rate": round(sum((not r["observed_side_effect"]) and (not r["observed_leak"]) and r["observed_decision"] in ("DENY", "REQUIRE_APPROVAL", "BLOCKED") for r in unauth) / max(1, len(unauth)), 4),
        "unauthorized_scenarios": len(unauth),
        "benign_false_positive_rate": round(sum(r["observed_decision"] != "ALLOW" or not r["passed"] for r in benign) / max(1, len(benign)), 4),
        "benign_scenarios": len(benign),
        "unauthorized_side_effects": sum(1 for r in unauth if r["observed_side_effect"]),
        "gateway_call_latency_ms": {"p50": pct(0.5), "p95": pct(0.95), "max": round(lat[-1], 2) if lat else None, "n": len(lat)},
        "note": "Latency measured on the sandbox/FakeClock harness with scrypt_n=2^10 and SQLite on local disk; not a production figure.",
    }
    return {"summary": summary, "rows": rows}


def regression(report: dict, baseline_path: Path) -> list[str]:
    if not baseline_path.exists():
        return []
    base = json.loads(baseline_path.read_text())
    cur = {r["id"]: r["passed"] for r in report["rows"]}
    return [f"{i}: passed in baseline, fails now" for i, ok in base.items() if ok and not cur.get(i, False)]


def to_markdown(rep: dict, reg: list[str]) -> str:
    s = rep["summary"]
    L = ["# AgentGuard benchmark report", "", f"*Generated by `python -m agentguard.benchmark.run`; results are from this run only.*", "",
         "## Summary", "", f"- Scenarios: **{s['passed']}/{s['scenarios']} passed**; categories covered: {s['categories_covered']}/{s['categories_total']}",
         f"- Attack success rate: **{s['attack_success_rate']:.1%}** over {s['attack_scenarios']} attack scenarios (success = unauthorized side effect, data leak, an expected-blocked call being allowed, or a failed safety check)",
         f"- Unauthorized-action block rate: **{s['unauthorized_action_block_rate']:.1%}** over {s['unauthorized_scenarios']} scenarios; unauthorized side effects observed: **{s['unauthorized_side_effects']}**",
         f"- Benign false-positive rate: **{s['benign_false_positive_rate']:.1%}** over {s['benign_scenarios']} benign scenarios",
         f"- Gateway latency (ms): p50 {s['gateway_call_latency_ms']['p50']}, p95 {s['gateway_call_latency_ms']['p95']}, max {s['gateway_call_latency_ms']['max']} (n={s['gateway_call_latency_ms']['n']}). {s['note']}",
         f"- Regressions vs baseline: {len(reg)}" + ("" if not reg else " — " + "; ".join(reg)), "",
         "## Scenarios", "", "| ID | Category | Initial identity/state | Request | Expected | Side effect allowed | Expected audit | Observed | Side effect | Pass |", "|---|---|---|---|---|---|---|---|---|---|"]
    for r in rep["rows"]:
        L.append(f"| {r['id']} | {r['category']}. {r['category_name']} | {r['initial']} | {r['request'].replace('|','/')} | {r['expected_decision']} | {'yes' if r['side_effect_allowed'] else 'no'} | {r['expected_audit'] or '—'} | {r['observed_decision']} | {'YES' if r['observed_side_effect'] else 'no'} | {'✅' if r['passed'] else '❌ ' + r['note']} |")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("--out", default="reports"); ap.add_argument("--save-baseline", action="store_true"); a = ap.parse_args()
    out = Path(a.out); out.mkdir(parents=True, exist_ok=True)
    rep = run_all()
    reg = regression(rep, Path("benchmarks/baseline.json"))
    (out / "benchmark.json").write_text(json.dumps(rep, indent=2), encoding="utf-8"); (out / "benchmark.md").write_text(to_markdown(rep, reg), encoding="utf-8")
    if a.save_baseline:
        Path("benchmarks").mkdir(exist_ok=True); Path("benchmarks/baseline.json").write_text(json.dumps({r["id"]: r["passed"] for r in rep["rows"]}, indent=2, encoding="utf-8"))
    print(json.dumps(rep["summary"], indent=2))
    for r in rep["rows"]:
        if not r["passed"]:
            print("FAIL", r["id"], r["title"], "| expected", r["expected_decision"], "got", r["observed_decision"], "| side_effect", r["observed_side_effect"], "| extra_ok", r["extra_check_ok"], "| audit_ok", r["audit_ok"], "|", r["note"])
